"""Derived views: ``learner.md`` (what the model reads at session start) and ``state.json``.

``learner.md`` shows **evidence, not decimals** (IDEA.md, *Review response*). Numbers stay
internal: the view names states, counts of independent vs assisted evidence, the last
delayed retrieval, transfer evidence, uncertainty and review priority. There is deliberately
no probability anywhere in it — ``no_decimals`` in the tests enforces that.

Both files are regenerated by code on every write. Nothing here is model-editable;
``notes.md`` is the one prose file the model owns, and only preferences live there.
"""

from __future__ import annotations

import json
